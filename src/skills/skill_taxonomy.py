def normalize_skill(skill):

    if not isinstance(skill, str):
        return None

    cleaned_skill = skill.strip().lower()

    for canonical_name, details in SKILL_TAXONOMY.items():

        all_names = [canonical_name.lower()] + details["aliases"]

        if cleaned_skill in all_names:
            return canonical_name

    return skill.strip()


def get_skill_category(skill):

    canonical_name = normalize_skill(skill)

    if canonical_name is None:
        return "Unknown"

    details = SKILL_TAXONOMY.get(canonical_name)

    if details is None:
        return "Unknown"

    return details["category"]
